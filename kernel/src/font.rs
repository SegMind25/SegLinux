//! SegOS 8x16 bitmap font (original artwork, drawn for SegOS).
//!
//! Every glyph is ASCII art below: 16 rows of 8 characters, `#` = pixel on,
//! `.` = pixel off. The art is converted to bitmaps at compile time by a
//! `const fn` parser; a malformed glyph (wrong row count, wrong row width,
//! stray character) is a compile error.
//!
//! Metrics: cell 8x16, cap height 10 (rows 3..=12), x-height 7 (rows 6..=12),
//! baseline at row 12, descenders in rows 13..=15, column 7 is spacing.

pub const WIDTH: usize = 8;
pub const HEIGHT: usize = 16;

/// Number of printable ASCII glyphs (0x20..=0x7E).
const ASCII_COUNT: usize = 95;
/// Table index of the fallback glyph.
const FALLBACK: usize = ASCII_COUNT;

/// Rows of the glyph for `c`, top to bottom; bit 7 is the leftmost pixel.
pub fn glyph(c: char) -> &'static [u8; HEIGHT] {
    let code = c as u32;
    if (0x20..=0x7E).contains(&code) {
        &GLYPHS[(code - 0x20) as usize]
    } else {
        &GLYPHS[FALLBACK]
    }
}

/// Parse one art string: a leading newline, then HEIGHT rows of WIDTH
/// characters of `#`/`.`, each row terminated by a newline, and nothing else.
const fn parse(art: &str) -> [u8; HEIGHT] {
    let b = art.as_bytes();
    assert!(
        b.len() == 1 + HEIGHT * (WIDTH + 1),
        "font art: glyph must be exactly 16 rows of 8 chars"
    );
    assert!(b[0] == b'\n', "font art: string must start with a newline");
    let mut out = [0u8; HEIGHT];
    let mut row = 0;
    while row < HEIGHT {
        let base = 1 + row * (WIDTH + 1);
        let mut col = 0;
        while col < WIDTH {
            match b[base + col] {
                b'#' => out[row] |= 0x80 >> col,
                b'.' => {}
                _ => panic!("font art: only '#' and '.' are allowed in a row"),
            }
            col += 1;
        }
        assert!(b[base + WIDTH] == b'\n', "font art: row must be 8 chars");
        row += 1;
    }
    out
}

const fn build() -> [[u8; HEIGHT]; ASCII_COUNT + 1] {
    let mut out = [[0u8; HEIGHT]; ASCII_COUNT + 1];
    let mut i = 0;
    while i < ASCII_COUNT + 1 {
        out[i] = parse(ART[i]);
        i += 1;
    }
    out
}

